package encapsulationConcepts;

public class Jewellery 
{
	 // private variables
    private int gms;
    private String design;

    // getter method for gms
    public int getGms() {
        return gms;
    }

    // setter method for gms
    public void setGms(int gms) {
        this.gms = gms;
    }

    // getter method for design
    public String getDesign() {
        return design;
    }

    // setter method for design
    public void setDesign(String design) {
        this.design = design;
    }
}


