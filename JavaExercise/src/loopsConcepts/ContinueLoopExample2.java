package loopsConcepts;

public class ContinueLoopExample2 
{
	 public static void main(String[] args){
	        int i=1;


	        while (i>7){
	            System.out.println(i);
	            i--;

	        }
	        do{
	            System.out.println();
	            System.out.println(i  + ")" + "Latha.G Automation Engg");
	            i++;
	            continue;

	        }while(i<9);

	        }

	    }


