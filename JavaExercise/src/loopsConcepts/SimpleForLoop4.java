package loopsConcepts;

public class SimpleForLoop4 
{
	public static void main(String[] args){
        for(int i = 1;i<=8;i++) {
            System.out.println(i);
            for(int j=0;j<=8;j++){
                System.out.println("");

            }
        }
        for(int y=8;y>=1;y--){
            System.out.println(y);

        }

    }
}


