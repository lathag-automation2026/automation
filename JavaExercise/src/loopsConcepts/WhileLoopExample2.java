package loopsConcepts;

public class WhileLoopExample2 
{
	 public static void main(String[] args) 
	 {
		 int i=14;
		 
		 while(i>7)
		 {
	            System.out.println(i);
	            i--;

		 }
		 do
		 {
	            System.out.println();
	            System.out.println(i + "inside do while loop printed");
	            i++;


		 }while(i<9);

		 
		 
	 }
}
